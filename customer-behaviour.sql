CREATE TABLE customer_shopping (
   customer_id INT PRIMARY KEY,
   age INT,
   gender VARCHAR(20),
   item_purchased VARCHAR(50),
   category VARCHAR(50),
   purchase_amount INT,
   location VARCHAR(100),
   size VARCHAR(10),
   color VARCHAR(30),
   season VARCHAR(20),
   review_rating DECIMAL(3,1),
   subscription_status VARCHAR(10),
   shipping_type VARCHAR(50),
   discount_applied VARCHAR(10),
   previous_purchase INT,
   payment_method VARCHAR(50),
   frequency_of_purchase VARCHAR(30),
   age_group VARCHAR(30),
   purchase_frequency_day INT
   );

   SELECT * FROM customer_shopping

   -- 1. Revenue Analysis -
   --compare total revenue generated by male and female customers.
   SELECT gender , sum(purchase_amount) as revenue
   from  customer_shopping
   group by gender;


   
--2. Discount & spending Analysis - 
--identified discount users whose purchase amount were at or above the overall average
select customer_id, purchase_amount
from customer_shopping
where discount_applied='yes'
and purchase_amount>=(select avg(purchase_amount) from customer_shopping);

--3. product rating analysis -
-- ranked the top 5 product by average review rating.
select item_purchased,
round(avg(review_rating)::numeric,2) as "Average product Rating"
from customer_shopping
group by item_purchased
order by avg(review_rating) desc
limit 5

--4. shipping analysis  - 
--compared average purchase amount for standard and express shipping.

select shipping_type, round(avg(purchase_amount),2)
from customer_shopping
where shipping_type in ('Standard' , 'Express')
group by shipping_type;

--5. subscription Analysis-
--compared customer counts, average spending , and total revenue between subscribers and non - subscribers 

select subscription_status,count(customer_id) as total_customers,
round(avg(purchase_amount),2) as avg_spend,
round(sum(purchase_amount),2) as total_revenue
from customer_shopping
group by subscription_status
order by total_revenue, avg_spend desc;


--6. diascount dependency analysis -
--identified the top 5 product by percentage of purchase with discounts applied

select item_purchased,
round(
100.0*sum(
case when discount_applied = 'Yes' then 1
else 0 end)/count(*),2)
as discount_rate
from customer_shopping
group by item_purchased
order by discount_rate desc 
limit 5;

--7.CUSTOMER SEGMENTATION - 
--classifed customer into new, returning and loyal segmnets based on previous purchase.

with customer_type as (
    select customer_id, previous_purchase,
    case when previous_purchase = 1 then 'New'
         when previous_purchase between 2 and 10 then 'Returning'
         else 'Loyal'
    end as customer_segment
    from customer_shopping
)
select customer_segment,
       count(*) as "Number of Customers" 
from customer_type
group by customer_segment;


--8. product popularity analysis-
--identified the top 3 most purchased products within each category
with item_counts as
( select category,
item_purchased,
count(customer_id) as total_orders,
row_number() over (partition by category order by count(customer_id) desc) as item_rank
from customer_shopping
group by category, item_purchased
)
select item_rank, category, item_purchased, total_orders
from item_counts
where item_Rank<=3;









